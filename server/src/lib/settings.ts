import type { Sql } from '../db.js';
import type { Role } from './session.js';

export interface SsoSettings {
  enabled: boolean;
  tenantId: string;
  clientId: string;
  /** Encrypted with APP_KEY; never sent to the browser. */
  clientSecretEnc: string;
  /** Optional Entra group object id; when set, only members may sign in. */
  allowedGroupId: string;
  autoProvision: boolean;
  defaultRole: Role;
}

export type MailSecurity = 'tls' | 'starttls' | 'none';

export interface MailSettings {
  enabled: boolean;
  host: string;
  port: number;
  /** tls = implicit TLS (usually 465), starttls = upgrade (usually 587, required), none = plain (local relay only). */
  security: MailSecurity;
  /** Verify the certificate of the mail server. Only switch off for a relay with a self-signed certificate. */
  verifyCertificate: boolean;
  username: string;
  passwordEnc: string;
  fromName: string;
  fromAddress: string;
  replyTo: string;
  dkim: { enabled: boolean; domain: string; selector: string; privateKeyEnc: string; publicKey: string };
}

export const notifyEvents = [
  'streamDown', 'outputFailed', 'mediaServerDown', 'backupFailed', 'backupSucceeded', 'updateFinished', 'updateAvailable',
] as const;
export type NotifyEvent = (typeof notifyEvents)[number];

export interface NotificationSettings {
  /** Extra addresses; administrators who opted in are added automatically. */
  recipients: string[];
  /** Send to all active administrators as well. */
  includeAdmins: boolean;
  events: Record<NotifyEvent, boolean>;
}

export type BackupProtocol = 'ftp' | 'ftps' | 'ftps-implicit' | 'scp';

export interface BackupTarget {
  protocol: BackupProtocol;
  host: string;
  port: number;
  username: string;
  passwordEnc: string;
  /** scp: private key (OpenSSH format) generated by Restream or pasted in. */
  privateKeyEnc: string;
  publicKey: string;
  /** scp: SHA-256 fingerprint of the server host key, pinned at the first successful connection. */
  hostKeySha256: string;
  /** ftps: verify the server certificate. */
  verifyCertificate: boolean;
  /** Remote directory, created when missing. */
  path: string;
}

export interface BackupSettings {
  /** Automatic backups on the schedule below. Manual backups work regardless. */
  scheduleEnabled: boolean;
  /** Server local time, HH:MM. */
  time: string;
  full: 'daily' | 'weekly' | 'monthly';
  /** 0 = Sunday … 6 = Saturday (weekly full backup). */
  fullWeekday: number;
  incremental: 'off' | 'daily' | 'every6h' | 'hourly';
  /** Number of full backup chains (a full backup plus its incrementals) to keep on the remote. */
  keepChains: number;
  /** Backups are always encrypted (AES-256-GCM) with a key derived from this passphrase. */
  passphraseEnc: string;
  target: BackupTarget;
}

export const oauthProviders = ['youtube', 'facebook', 'twitch', 'x'] as const;
export type OAuthProvider = (typeof oauthProviders)[number];

/** OAuth app (client) of a platform, registered by the administrator in the platform's developer console. */
export interface OAuthApp { clientId: string; clientSecretEnc: string }

export interface RecordingSettings {
  /** Finished recordings older than this many days are deleted automatically (0 = keep forever). */
  retentionDays: number;
}

export interface Settings {
  instanceName: string;
  defaultLanguage: 'en' | 'nl';
  /** Public base URL, e.g. https://restream.example.com (used for SSO redirects). */
  publicUrl: string;
  /** Optional GitHub token, only needed when the repository is private. */
  githubTokenEnc: string;
  sso: SsoSettings;
  mail: MailSettings;
  notifications: NotificationSettings;
  backup: BackupSettings;
  platforms: Record<OAuthProvider, OAuthApp>;
  recordings: RecordingSettings;
}

